def _normalize(values: list[float], log_scale: bool = False) -> list[float]:
    xs = [math.log1p(v) for v in values] if log_scale else list(values)
    lo, hi = min(xs), max(xs)
    span = hi - lo if hi > lo else 1.0
    # Map to a 10-100 range rather than 0-100 so even the smallest/slowest
    # animal in the roster keeps a nonzero combat presence.
    return [10 + 90 * (x - lo) / span for x in xs]


def build() -> tuple[list[dict], list[dict]]:
    weights = [a["avg_weight_kg"] for a in RAW_ANIMALS]
    speeds = [a["top_speed_kmh"] for a in RAW_ANIMALS]
    size_scores = _normalize(weights, log_scale=True)
    speed_scores = _normalize(speeds, log_scale=False)

    animals = []
    for animal, size_score, speed_score in zip(RAW_ANIMALS, size_scores, speed_scores):
        combat_attributes = {
            "size": round(size_score, 1),
            "strength": float(animal["strength_est"]),
            "speed": round(speed_score, 1),
            "agility": float(animal["agility_est"]),
            "defense": float(animal["defense_est"]),
            "weapon": float(animal["weapon_est"]),
            "endurance": float(animal["endurance_est"]),
        }
        attribute_sources = {
            "size": "derived",       # normalized from measured weight/length
            "strength": "estimated",
            "speed": "derived",      # normalized from measured top speed
            "agility": "estimated",
            "defense": "estimated",
            "weapon": "estimated",
            "endurance": "estimated",
        }
        animals.append({
            "id": animal["id"],
            "common_name": animal["common_name"],
            "scientific_name": animal["scientific_name"],
            "category": animal["category"],
            "diet": animal["diet"],
            "fighting_style": animal["fighting_style"],
            "description": animal["description"],
            "avg_weight_kg": animal["avg_weight_kg"],
            "max_weight_kg": animal["max_weight_kg"],
            "avg_length_m": animal["avg_length_m"],
            "top_speed_kmh": animal["top_speed_kmh"],
            "bite_force_psi": animal["bite_force_psi"],
            "natural_weapons": animal["natural_weapons"],
            "habitats": animal["habitats"],
            "adaptations": animal["adaptations"],
            "combat_attributes": combat_attributes,
            "attribute_sources": attribute_sources,
        })
    return animals, ENVIRONMENTS


def main() -> None:
    animals, environments = build()
    (OUT_DIR / "animals.json").write_text(json.dumps(animals, indent=2))
    (OUT_DIR / "environments.json").write_text(json.dumps(environments, indent=2))
    print(f"Wrote {len(animals)} animals and {len(environments)} environments to {OUT_DIR}")


if __name__ == "__main__":
    main()
